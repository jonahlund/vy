pub fn is_known_void_tag(name: &str) -> bool {
    const KNOWN_VOID_TAGS: &[&str] = &[
        "area", "base", "br", "col", "embed", "hr", "img", "input", "link",
        "meta", "source", "track", "wbr",
    ];
    KNOWN_VOID_TAGS.contains(&name)
}

